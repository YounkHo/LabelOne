export function translateUiText(value: string, language: UiLanguage): string {
  if (!value) return value;
  const leading = value.match(/^\s*/)?.[0] ?? '';
  const trailing = value.match(/\s*$/)?.[0] ?? '';
  const core = value.slice(leading.length, value.length - trailing.length || undefined);
  if (language === 'zh-CN') {
    const translated = exactChinese[core] ?? core;
    return `${leading}${translated}${trailing}`;
  }
  let translated = exactEnglish[core] ?? core;
  if (translated === core) {
    translated = translated
      .replace(/(\d+)\s*分钟前/g, '$1 minutes ago')
      .replace(/(\d+)\s*小时前/g, '$1 hours ago')
      .replace(/(\d+)\s*天前/g, '$1 days ago')
      .replace(/(\d+)\s*个项目/g, '$1 projects')
      .replace(/(\d+)\s*张(?=\s|$)/g, '$1 images')
      .replace(/(\d+)\s*项(?=\s|$)/g, '$1 items');
    for (const [source, target] of phraseEnglish) translated = translated.replaceAll(source, target);
  }
  return `${leading}${translated}${trailing}`;
}
